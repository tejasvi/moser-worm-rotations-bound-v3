#!/usr/bin/env python3
"""Emit WormCore/Family.lean: the family arcs (exact), the global vertex map, the root box (mantissas at 2^-120),
the cell grid and tau (the header value, read as its shortest decimal), from a part header of the frozen certificate.
usage: python3 -B gen_family.py CERTDIR OUT"""
import sys, os, json
from fractions import Fraction as Fr
cert, out = sys.argv[1], sys.argv[2]
h = json.load(open(os.path.join(cert, 'part0000.json')))
fs = h['famspec']
def q(x):
    f = Fr(x); return f'({f.numerator}, {f.denominator})'
def m(x):
    f = Fr(float(x)) * (1 << 120); assert f.denominator == 1; return int(f)
def lit(i): return f'({i})' if i < 0 else str(i)
arcs = []
for a in fs['arcs']:
    steps = ', '.join(f'({Fr(l).numerator}, {Fr(l).denominator}, {int(Fr(d))})' for l, d in zip(a['lengths'], a['dirs_deg']))
    arcs.append(f'  {{ sx := {q(a["start"][0])}, sy := {q(a["start"][1])}, steps := [{steps}] }}')
tdec = repr(float(h['tau']))                 # shortest decimal of the header value, e.g. '0.24'
assert tdec.startswith('0.') and tdec[2:].isdigit()
tnum, tden = int(tdec[2:]), 10 ** len(tdec[2:])
tau = Fr(tnum, tden) * (1 << 56); tauHi = -((-tau.numerator) // tau.denominator)
cname = os.path.basename(os.path.normpath(cert))
L = ['import WormCore.Tree', '', '/-! The family, the root box and the cell grid of the worm certificate ' + cname + ' (from its part headers;',
     'generated by tools/gen_family.py). -/', '', 'namespace WormCore', '',
     '/-- The five arcs: the unit segment, the two-link worm, the three-link arc, and two Z-shapes. -/',
     'def famArcs : List Arc := [', ',\n'.join(arcs), ']', '',
     '/-- Global vertex ids: `(body, polyline vertex)`. -/',
     'def famGid : List (Nat × Nat) := [' + ', '.join(f'({b}, {j})' for b, j in h['gid_map']) + ']', '',
     '/-- The root box (mantissas at `2⁻¹²⁰`) and the cells. -/',
     'def rootW : Root := {',
     '  lo := #[' + ', '.join(lit(m(x)) for x in h['lo']) + '],',
     '  hi := #[' + ', '.join(lit(m(x)) for x in h['hi']) + '],',
     '  split0 := #[' + ', '.join(str(int(x)) for x in h['split0']) + '],',
     f'  nparts := {int(h["nparts"])} }}', '',
     f'/-- An upper mantissa (scale `2⁻⁵⁶`) of `τ = {tnum}/{tden}`. -/', f'def tauHiW : Int := {tauHi}', '',
     f'/-- Lists of at most `maxsmall` points are "small" (the small-list lemma). -/', f'def maxsmallW : Nat := {int(h["maxsmall"])}', '',
     '/-- The family data of the checker. -/', 'def famW : Fam := mkFam famArcs famGid', '',
     '/-- Local refinement depth of the leaf test (`leafOKR`). -/', 'def rdepthW : Nat := 6', '',
     'end WormCore', '']
open(out, 'w').write('\n'.join(L))
print('ok')
