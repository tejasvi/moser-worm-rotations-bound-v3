#!/usr/bin/env python3
"""Generate the native-track shard modules WormN/ from the converted worm certificate data (data/).

  WormN/Skel/GNNN.lean    the skeletons of parts [NNN*G, (NNN+1)*G) via include_str (def skelGNNN : Array String)
  WormN/Skel.lean         def skelOf (p : Nat) : String, the skeleton of part p ("" out of range)
  WormN/Units/GNNN.lean   the (p, u) lists units_cNNNNN of chunks [NNN*K, (NNN+1)*K) and unitsG_NNN, their list
  WormN/Chunk/CNNNNN.lean txt_cNNNNN (include_str) and
                          theorem chunk_cNNNNN : chunkCheck famW rootW maxsmallW tauHiW rdepthW skelOf txt_cNNNNN
                            = some units_cNNNNN := by native_decide
  WormN/AllUnits.lean     def allUnits : every (p, u) of every part, from the skeletons;
                          def unitLists := unitsG_000 ++ unitsG_001 ++ ... (the chunks' unit lists in chunk order)
  WormN/Cover.lean        theorem skel_ok : every part's skeleton walk succeeds (native_decide)
                          theorem cover : allUnits = unitLists.flatten (native_decide)
  WormN/Group/GNNN.lean   theorem groupOK_NNN : ∀ L ∈ unitsG_NNN, ∃ txt, chunkCheck ... txt = some L (kernel proof)
  WormN/All.lean          theorem chunks_ok : ∀ L ∈ unitLists, ∃ txt, chunkCheck ... txt = some L (kernel proof)

All definitions live in namespace WormN. The Units docstrings give the converter's leaf counts; a chunk module's
docstring gives its current count (after leaf patches, see tools/wpatch.py). Data paths in include_str are relative to the module file (data at ROOT/data).
The manifest is data/manifest.json: either the list written by tools/wconvert.py (one entry per chunk with "chunk",
"units", "leaves", "bytes") or a dict with "chunks": [{"name": "cNNNNN", "units": [[p, u], ...], "leaves": n, ...}].

usage: python3 -I -B wshards.py ROOT [--data DATA] [--nparts N] [--skel-group G] [--units-group K] [--chunks A:B]
"""
import argparse
import json
import os


def wrap_join(items, sep=', ', indent='  ', width=118):
    """join items with sep into lines of at most `width` characters (lines break after a separator)"""
    lines = []
    cur = indent
    for i, it in enumerate(items):
        piece = it + (sep if i + 1 < len(items) else '')
        if len(cur) + len(piece.rstrip()) > width and cur.strip():
            lines.append(cur.rstrip())
            cur = indent
        cur += piece
    if cur.strip():
        lines.append(cur.rstrip())
    return '\n'.join(lines)


def write_if_changed(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path):
        with open(path) as f:
            if f.read() == text:
                return False
    tmp = path + '.tmp'
    with open(tmp, 'w') as f:
        f.write(text)
    os.replace(tmp, path)
    return True


def load_chunks(data):
    m = json.load(open(os.path.join(data, 'manifest.json')))
    if isinstance(m, list):
        chunks = [dict(name=f"c{e['chunk']:05d}", units=e['units'], leaves=e['leaves']) for e in m]
        counts = {}
    else:
        chunks = m['chunks']
        counts = m.get('counts', {})
    for k, c in enumerate(chunks):
        assert c['name'] == f'c{k:05d}', (k, c['name'])
    return chunks, counts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('root')
    ap.add_argument('--data', default=None, help='data dir (default ROOT/data); include_str paths assume ROOT/data')
    ap.add_argument('--nparts', type=int, default=None)
    ap.add_argument('--skel-group', type=int, default=256)
    ap.add_argument('--units-group', type=int, default=64)
    ap.add_argument('--chunks', default=None, help='A:B, only these chunk modules (Cover needs all)')
    a = ap.parse_args()
    root = a.root
    data = a.data or os.path.join(root, 'data')
    chunks, counts = load_chunks(data)
    nparts = a.nparts or counts.get('parts') or len([f for f in os.listdir(os.path.join(data, 'skel'))
                                                      if f.startswith('s') and f.endswith('.txt')])
    for p in range(nparts):
        assert os.path.exists(os.path.join(data, 'skel', f's{p:05d}.txt')), p
    G = a.skel_group
    K = a.units_group
    ngroups = (nparts + G - 1) // G
    nug = (len(chunks) + K - 1) // K
    wn = os.path.join(root, 'WormN')
    nchanged = 0

    # skeleton groups
    for g in range(ngroups):
        p0, p1 = g * G, min(nparts, (g + 1) * G)
        items = [f'include_str "../../data/skel/s{p:05d}.txt"' for p in range(p0, p1)]
        text = (f'/-! Skeletons of parts {p0}-{p1 - 1} of the worm certificate (generated by tools/wshards.py). -/\n\n'
                f'namespace WormN\n\n'
                f'/-- The skeletons of parts {p0}-{p1 - 1}, in order. -/\n'
                f'def skelG{g:03d} : Array String := #[\n  ' + ',\n  '.join(items) + ']\n\nend WormN\n')
        nchanged += write_if_changed(os.path.join(wn, 'Skel', f'G{g:03d}.lean'), text)
    imports = '\n'.join(f'import WormN.Skel.G{g:03d}' for g in range(ngroups))
    groups = wrap_join([f'skelG{g:03d}' for g in range(ngroups)])
    text = (f'{imports}\n\n'
            f'/-! The skeletons of all {nparts} parts (generated by tools/wshards.py). -/\n\n'
            f'namespace WormN\n\n'
            f'/-- The skeleton groups, {G} parts each. -/\n'
            f'def skelGroups : Array (Array String) := #[\n{groups}]\n\n'
            f'/-- The skeleton of part `p` (`""` if `p` is out of range). -/\n'
            f'def skelOf (p : Nat) : String := (skelGroups.getD (p / {G}) #[]).getD (p % {G}) ""\n\n'
            f'end WormN\n')
    nchanged += write_if_changed(os.path.join(wn, 'Skel.lean'), text)

    # unit lists, grouped (so that AllUnits and Cover do not import the chunk texts)
    for g in range(nug):
        c0, c1 = g * K, min(len(chunks), (g + 1) * K)
        body = []
        for k in range(c0, c1):
            c = chunks[k]
            us = wrap_join([f'({p}, {u})' for p, u in c['units']])
            body.append(f'/-- The units of chunk {c["name"]} ({len(c["units"])} units, '
                        f'{c.get("leaves_converted", c["leaves"])} leaves). -/\n'
                        f'def units_{c["name"]} : List (Nat × Nat) := [\n{us}]\n')
        lists = wrap_join([f'units_{chunks[k]["name"]}' for k in range(c0, c1)])
        body.append(f'/-- The unit lists of chunks c{c0:05d}-c{c1 - 1:05d}, in chunk order. -/\n'
                    f'def unitsG_{g:03d} : List (List (Nat × Nat)) := [\n{lists}]\n')
        text = (f'/-! The unit lists of chunks c{c0:05d}-c{c1 - 1:05d} (generated by tools/wshards.py). -/\n\n'
                f'-- list literals of up to {max(len(chunks[k]["units"]) for k in range(c0, c1))} elements\n'
                f'set_option maxRecDepth 100000\n\n'
                f'namespace WormN\n\n' + '\n'.join(body) + '\nend WormN\n')
        nchanged += write_if_changed(os.path.join(wn, 'Units', f'G{g:03d}.lean'), text)

    # chunk modules
    k0, k1 = (0, len(chunks)) if a.chunks is None else (int(x) for x in a.chunks.split(':'))
    for k in range(k0, k1):
        c = chunks[k]
        n = c['name']
        (p0, u0), (p1, u1) = c['units'][0], c['units'][-1]
        nleaves = f'{c["leaves"]} leaves'
        if c.get('leaves_converted', c['leaves']) != c['leaves']:
            nleaves += f' ({c["leaves"] - c["leaves_converted"]} added by a leaf patch, see data/manifest.json)'
        text = (f'import WormCore.Family\nimport WormN.Skel\nimport WormN.Units.G{k // K:03d}\n\n'
                f'/-! Chunk {n} of the worm certificate: units ({p0}, {u0})-({p1}, {u1}), {nleaves}\n'
                f'(generated by tools/wshards.py). -/\n\n'
                f'namespace WormN\n\nopen WormCore\n\n'
                f'/-- The text of chunk {n}. -/\n'
                f'def txt_{n} : String := include_str "../../data/chunks/{n}.txt"\n\n'
                f'theorem chunk_{n} :\n'
                f'    chunkCheck famW rootW maxsmallW tauHiW rdepthW skelOf txt_{n} = some units_{n} := by\n'
                f'  native_decide\n\nend WormN\n')
        nchanged += write_if_changed(os.path.join(wn, 'Chunk', f'C{k:05d}.lean'), text)

    # groups of chunk theorems (kernel proofs, no native_decide)
    stmt = 'chunkCheck famW rootW maxsmallW tauHiW rdepthW skelOf txt = some L'
    for g in range(nug):
        c0, c1 = g * K, min(len(chunks), (g + 1) * K)
        imports = '\n'.join(f'import WormN.Chunk.C{k:05d}' for k in range(c0, c1))
        pf = wrap_join([f'⟨_, chunk_{chunks[k]["name"]}⟩' for k in range(c0, c1)] + ['fun _ h => nomatch h'],
                       indent='    ')
        text = (f'{imports}\n\n'
                f'/-! The chunk theorems of chunks c{c0:05d}-c{c1 - 1:05d} (generated by tools/wshards.py). -/\n\n'
                f'namespace WormN\n\nopen WormCore\n\n'
                f'/-- Every unit list of group {g:03d} is the result of a successful chunk check. -/\n'
                f'theorem groupOK_{g:03d} : ∀ L ∈ unitsG_{g:03d}, ∃ txt, {stmt} := by\n'
                f'  simp only [unitsG_{g:03d}, List.forall_mem_cons]\n'
                f'  exact ⟨\n{pf}⟩\n\n'
                f'end WormN\n')
        nchanged += write_if_changed(os.path.join(wn, 'Group', f'G{g:03d}.lean'), text)

    # all units, the unit lists, the cover
    imports = '\n'.join(['import WormCore.Family', 'import WormN.Skel'] +
                        [f'import WormN.Units.G{g:03d}' for g in range(nug)])
    ul = wrap_join([f'unitsG_{g:03d}' for g in range(nug)], sep=' ++ ', indent='  ')
    text = (f'{imports}\n\n'
            '/-! The list of all units, from the skeletons, and the unit lists of all chunks in chunk order\n'
            '(generated by tools/wshards.py). -/\n\n'
            'namespace WormN\n\nopen WormCore\n\n'
            '/-- Every unit `(p, u)` of every part `p < rootW.nparts`, `u` ascending. -/\n'
            'def allUnits : List (Nat × Nat) :=\n'
            '  (List.range rootW.nparts).flatMap fun p =>\n'
            '    (List.range ((unitBoxes rootW p (skelOf p)).getD #[]).size).map (p, ·)\n\n'
            f'/-- The unit lists of the {len(chunks)} chunks, in chunk order. -/\n'
            f'def unitLists : List (List (Nat × Nat)) :=\n{ul}\n\n'
            'end WormN\n')
    nchanged += write_if_changed(os.path.join(wn, 'AllUnits.lean'), text)
    text = ('import WormN.AllUnits\n\n'
            '/-! The skeleton of every part is well formed, and the chunks list every unit, in order\n'
            '(generated by tools/wshards.py). -/\n\n'
            'namespace WormN\n\nopen WormCore\n\n'
            '/-- The skeleton walk of every part succeeds. -/\n'
            'theorem skel_ok : (List.range rootW.nparts).all (fun p => (unitBoxes rootW p (skelOf p)).isSome) = true := by\n'
            '  native_decide\n\n'
            '/-- The chunks list every unit, in order. -/\n'
            'theorem cover : allUnits = unitLists.flatten := by\n'
            '  native_decide\n\n'
            'end WormN\n')
    nchanged += write_if_changed(os.path.join(wn, 'Cover.lean'), text)

    # every chunk check, over all unit lists (kernel proof, no native_decide)
    imports = '\n'.join([f'import WormN.Group.G{g:03d}' for g in range(nug)] + ['import WormN.Cover'])
    pf = f'groupOK_000'
    for g in range(1, nug):
        pf = f'⟨{pf}, groupOK_{g:03d}⟩'
    pf = wrap_join(pf.split(', '), sep=', ', indent='    ').lstrip()
    simp = 'simp only [unitLists, List.forall_mem_append]' if nug > 1 else 'simp only [unitLists]'
    text = (f'{imports}\n\n'
            f'/-! Every unit list of the {len(chunks)} chunks is the result of a successful chunk check\n'
            f'(generated by tools/wshards.py). -/\n\n'
            f'namespace WormN\n\nopen WormCore\n\n'
            f'/-- Every unit list is the result of a successful chunk check. -/\n'
            f'theorem chunks_ok : ∀ L ∈ unitLists, ∃ txt, {stmt} := by\n'
            f'  {simp}\n'
            f'  exact {pf}\n\n'
            f'end WormN\n')
    nchanged += write_if_changed(os.path.join(wn, 'All.lean'), text)
    print(f'parts {nparts} skel groups {ngroups} chunks {len(chunks)} unit groups {nug} '
          f'chunk modules {k1 - k0} files changed {nchanged}')


if __name__ == '__main__':
    main()
